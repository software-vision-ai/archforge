//! Checks the catalogues' shape at build time so a malformed row fails the build rather than a
//! lookup, and embeds the interface faces from the optional fonts input (`CRAFT_FONTS_DIR`).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The faces of the fonts input the interface draws with: the design's Inter, in the two weights
/// it uses.
const FACES: &[(&str, &str)] = &[("Inter", "Regular"), ("Inter", "SemiBold")];

fn main() {
    faces();
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
    let i18n = Path::new(&manifest).join("src").join("i18n");
    println!("cargo:rerun-if-changed={}", i18n.display());
    let Ok(entries) = std::fs::read_dir(&i18n) else { return };
    for path in entries.flatten().map(|e| e.path()).filter(|p| p.extension().is_some_and(|e| e == "tsv")) {
        let text = std::fs::read_to_string(&path).unwrap_or_default();
        for (n, line) in text.lines().enumerate().filter(|(_, l)| !l.is_empty() && !l.starts_with('#')) {
            let cols = line.split('\t').count();
            if cols != 4 {
                println!("cargo:warning={}:{}: a catalogue row has 4 tab-separated columns, found {cols}", path.display(), n + 1);
                std::process::exit(1);
            }
        }
    }
}

/// Writes `faces.rs`: one `Face` per wanted face the fonts input lists, none without the input.
/// An input that is set but unreadable is a warning, or an error with `CRAFT_FONTS_REQUIRED`.
fn faces() {
    println!("cargo:rerun-if-env-changed=CRAFT_FONTS_DIR");
    println!("cargo:rerun-if-env-changed=CRAFT_FONTS_REQUIRED");
    let mut src = String::from("/// The interface faces from the fonts input (generated by build.rs).\npub static FACES: &[Face] = &[\n");
    if let Some(dir) = std::env::var_os("CRAFT_FONTS_DIR").map(PathBuf::from) {
        match listed_faces(&dir) {
            Ok(entries) => src.push_str(&entries),
            Err(e) if std::env::var_os("CRAFT_FONTS_REQUIRED").is_some() => {
                println!("cargo:warning=CRAFT_FONTS_DIR={}: {e}", dir.display());
                std::process::exit(1);
            }
            Err(e) => println!("cargo:warning=building without the fonts input: CRAFT_FONTS_DIR={}: {e}", dir.display()),
        }
    }
    src.push_str("];\n");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("faces.rs");
    if let Err(e) = std::fs::write(&out, src) {
        println!("cargo:warning=could not write the faces: {e}");
        std::process::exit(1);
    }
}

/// The fonts input's manifests: the main one, and the Latin one that lists Inter.
const MANIFESTS: &[&str] = &["manifest.txt", "latin-manifest.txt"];

/// The `Face { .. }` initialisers for the wanted faces the manifests list; a wanted face they lack
/// is an error, so a build with the input never silently draws another face.
fn listed_faces(dir: &Path) -> Result<String, String> {
    let mut text = String::new();
    for name in MANIFESTS {
        let manifest = dir.join("fonts").join(name);
        println!("cargo:rerun-if-changed={}", manifest.display());
        match std::fs::read_to_string(&manifest) {
            Ok(t) => text.push_str(&t),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(format!("{}: {e}", manifest.display())),
        }
        text.push('\n');
    }
    let mut out = String::new();
    let mut found = 0;
    for line in text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let fields: Vec<&str> = line.split(" | ").map(str::trim).collect();
        let [family, style, file, ..] = fields.as_slice() else {
            return Err(format!("malformed manifest line: {line}"));
        };
        if !FACES.contains(&(*family, *style)) {
            continue;
        }
        let path = dir.join(file).canonicalize().map_err(|e| format!("{file}: {e}"))?;
        println!("cargo:rerun-if-changed={}", path.display());
        let _ = writeln!(out, "    Face {{ family: {family:?}, style: {style:?}, bytes: include_bytes!({:?}) }},", path.display().to_string());
        found += 1;
    }
    if found < FACES.len() {
        return Err(format!("the manifest lists {found} of the faces {FACES:?}"));
    }
    Ok(out)
}
