//! The attribution check.
//!
//! Walks `assets/`; requires one `[[asset]]` row per file in
//! `ATTRIBUTION.toml` (path, author, source with version, licence, sha256); checks every hash, that
//! every licence named has its text in the tree (the `[licences]` table maps a licence to its
//! files), and that no file name contains a name from the trademark list when it is there.
//! `ATTRIBUTION.md` is generated
//! from the manifest and never edited by hand: `cargo xtask assets` rewrites it, and the gate's
//! `--check` fails when it is stale.
//!
//! `[[face]]` rows name the fonts the program carries and draws with (face, author, copyright
//! notice, source, licence). Their licences need their text in the tree too. A face that comes in a
//! crate also names the crate and its version, which must be the one `Cargo.lock` holds, so an
//! upgrade that changes the faces fails the check until the rows are reviewed.

use std::collections::{BTreeMap, BTreeSet};

use crate::util;

pub const FOLDERS: &[&str] = &["assets"];
const FIELDS: &[&str] = &["path", "author", "source", "licence", "sha256"];
const FACE_FIELDS: &[&str] = &["face", "author", "copyright", "source", "licence"];

/// The generated `ATTRIBUTION.md` for these rows and faces.
pub fn render(rows: &[BTreeMap<String, String>], faces: &[BTreeMap<String, String>]) -> String {
    let mut out = String::from("# Attribution\n\nGenerated by `cargo xtask assets` from `ATTRIBUTION.toml`; do not edit by hand.\n\n");
    out.push_str("| Path | Author | Source | Licence | SHA-256 |\n|---|---|---|---|---|\n");
    for r in rows {
        let get = |k: &str| r.get(k).map(String::as_str).unwrap_or_default();
        out.push_str(&format!("| `{}` | {} | {} | {} | `{}` |\n", get("path"), get("author"), get("source"), get("licence"), get("sha256")));
    }
    if !faces.is_empty() {
        out.push_str("\n## Fonts\n\n");
        out.push_str("The program carries these faces and draws its text with them; their licence texts are in `licenses/fonts/`.\n\n");
        out.push_str("| Face | Author | Copyright | Source | Licence |\n|---|---|---|---|---|\n");
        for r in faces {
            let get = |k: &str| r.get(k).map(String::as_str).unwrap_or_default();
            out.push_str(&format!("| {} | {} | {} | {} | {} |\n", get("face"), get("author"), get("copyright"), get("source"), get("licence")));
        }
    }
    out
}

pub fn run(check: bool) -> Result<(), String> {
    let root = util::root();
    let text = std::fs::read_to_string(root.join("ATTRIBUTION.toml")).map_err(|e| format!("ATTRIBUTION.toml: {e}"))?;
    let tables = util::toml(&text).map_err(|e| format!("ATTRIBUTION.toml: {e}"))?;
    let rows: Vec<BTreeMap<String, String>> = tables.iter().filter(|t| t.array && t.name == "asset").map(|t| t.values.clone()).collect();
    let faces: Vec<BTreeMap<String, String>> = tables.iter().filter(|t| t.array && t.name == "face").map(|t| t.values.clone()).collect();
    let licences: BTreeMap<String, String> = tables.iter().find(|t| !t.array && t.name == "licences").map(|t| t.values.clone()).unwrap_or_default();
    // File names are held to the trademark list when it is there; without it the gate says the
    // trademark check was skipped.
    let brands = if util::brand_list_path().is_some() { util::brands()? } else { Vec::new() };
    let mut problems = Vec::new();

    let mut files = Vec::new();
    for folder in FOLDERS {
        files.extend(util::walk(&root.join(folder)));
    }
    for file in &files {
        let rel = file.to_string_lossy().replace('\\', "/");
        let lower = rel.to_lowercase();
        if let Some(b) = brands.iter().find(|b| lower.contains(b.as_str())) {
            problems.push(format!("{rel}: the file name contains the listed name {b:?}"));
        }
        let Some(row) = rows.iter().find(|r| r.get("path").is_some_and(|p| *p == rel)) else {
            problems.push(format!("{rel}: no attribution row in ATTRIBUTION.toml"));
            continue;
        };
        let bytes = std::fs::read(root.join(&rel)).map_err(|e| format!("{rel}: {e}"))?;
        let hash = sha256_hex(&bytes);
        if row.get("sha256") != Some(&hash) {
            problems.push(format!("{rel}: the recorded hash does not match the file (sha256 {hash})"));
        }
    }
    for row in &rows {
        let path = row.get("path").cloned().unwrap_or_default();
        for field in FIELDS {
            if row.get(*field).is_none_or(|v| v.is_empty()) {
                problems.push(format!("ATTRIBUTION.toml: the row for {path:?} has no {field}"));
            }
        }
        if !root.join(&path).is_file() {
            problems.push(format!("ATTRIBUTION.toml: {path:?} does not exist"));
        }
        licence_texts(&root, &licences, row, &mut problems);
    }
    let locked = if faces.iter().all(|f| !f.contains_key("crate")) {
        BTreeSet::new()
    } else {
        locked_packages(&std::fs::read_to_string(root.join("Cargo.lock")).map_err(|e| format!("Cargo.lock: {e}"))?)
    };
    for row in &faces {
        let face = row.get("face").cloned().unwrap_or_default();
        for field in FACE_FIELDS {
            if row.get(*field).is_none_or(|v| v.is_empty()) {
                problems.push(format!("ATTRIBUTION.toml: the face row for {face:?} has no {field}"));
            }
        }
        if row.contains_key("crate") != row.contains_key("version") {
            problems.push(format!("ATTRIBUTION.toml: the face row for {face:?} names a crate without its version, or a version without its crate"));
        }
        problems.extend(face_version_problem(row, &locked));
        licence_texts(&root, &licences, row, &mut problems);
    }

    let generated = render(&rows, &faces);
    let current = std::fs::read_to_string(root.join("ATTRIBUTION.md")).unwrap_or_default();
    if current != generated {
        if check {
            problems.push("ATTRIBUTION.md is stale; run `cargo xtask assets`".into());
        } else {
            std::fs::write(root.join("ATTRIBUTION.md"), &generated).map_err(|e| format!("ATTRIBUTION.md: {e}"))?;
            println!("assets: ATTRIBUTION.md regenerated");
        }
    }
    if problems.is_empty() {
        println!("assets: {} file(s), {} row(s), {} face(s), all attributed", files.len(), rows.len(), faces.len());
        Ok(())
    } else {
        for p in &problems {
            eprintln!("assets: {p}");
        }
        Err(format!("{} attribution problem(s)", problems.len()))
    }
}

/// Every `name` and `version` pair of `Cargo.lock`'s `[[package]]` tables. The lock's multi-line
/// arrays are beyond `util::toml`, so only the two keys are read, line by line, and only inside a
/// package table: `[[patch.unused]]` tables have the same keys and lock nothing.
fn locked_packages(lock: &str) -> BTreeSet<(String, String)> {
    let mut out = BTreeSet::new();
    let mut in_package = false;
    let mut name: Option<String> = None;
    let quoted =
        |line: &str, key: &str| line.strip_prefix(key).and_then(|v| v.strip_prefix('"')).and_then(|v| v.strip_suffix('"')).map(str::to_string);
    for line in lock.lines().map(str::trim) {
        if line.starts_with('[') && !line.starts_with("[ ") {
            in_package = line == "[[package]]";
            name = None;
        } else if !in_package {
            continue;
        } else if let Some(v) = quoted(line, "name = ") {
            name = Some(v);
        } else if let Some(v) = quoted(line, "version = ")
            && let Some(n) = name.take()
        {
            out.insert((n, v));
        }
    }
    out
}

/// A face row's crate, when it names one, must be locked at its version, and its source must name
/// both, so the rows are reviewed when an upgrade may have changed the faces.
fn face_version_problem(row: &BTreeMap<String, String>, locked: &BTreeSet<(String, String)>) -> Option<String> {
    let face = row.get("face").map(String::as_str).unwrap_or_default();
    let (Some(krate), Some(version)) = (row.get("crate"), row.get("version")) else { return None };
    if !locked.contains(&(krate.clone(), version.clone())) {
        let held: Vec<&str> = locked.iter().filter(|(n, _)| n == krate).map(|(_, v)| v.as_str()).collect();
        return Some(format!(
            "ATTRIBUTION.toml: the face row for {face:?} names {krate} {version}, but Cargo.lock holds {}; review the face, its notice and its licence, then update the row",
            if held.is_empty() { "no such crate".to_string() } else { held.join(", ") }
        ));
    }
    let named = format!("{krate} {version}");
    // The version ends where the source's text goes on, so 0.36.20 never passes for 0.36.2.
    let names_it = |s: &String| {
        s.strip_prefix(&named)
            .is_some_and(|rest| rest.chars().next().is_none_or(|c| !(c.is_ascii_alphanumeric() || c == '.' || c == '-' || c == '+')))
    };
    if !row.get("source").is_some_and(names_it) {
        return Some(format!("ATTRIBUTION.toml: the face row for {face:?} has a source that does not start with {named:?}"));
    }
    None
}

/// A row's licence must have an entry in `[licences]` whose text files are in the tree.
fn licence_texts(root: &std::path::Path, licences: &BTreeMap<String, String>, row: &BTreeMap<String, String>, problems: &mut Vec<String>) {
    let licence = row.get("licence").cloned().unwrap_or_default();
    match licences.get(&licence) {
        None => problems.push(format!("ATTRIBUTION.toml: licence {licence:?} has no entry in [licences]")),
        Some(files) => {
            for f in files.split(',').map(str::trim).filter(|f| !f.is_empty()) {
                if !root.join(f).is_file() {
                    problems.push(format!("licence {licence:?}: its text {f} is missing"));
                }
            }
        }
    }
}

/// SHA-256 of `bytes`, as lower-case hex.
pub fn sha256_hex(bytes: &[u8]) -> String {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be,
        0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa,
        0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85,
        0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3,
        0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f,
        0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
    ];
    let mut h: [u32; 8] = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
    let mut data = bytes.to_vec();
    let bit_len = (bytes.len() as u64).wrapping_mul(8);
    data.push(0x80);
    while data.len() % 64 != 56 {
        data.push(0);
    }
    data.extend_from_slice(&bit_len.to_be_bytes());
    for block in data.chunks(64) {
        let mut w = [0u32; 64];
        for (i, word) in block.chunks(4).enumerate().take(16) {
            w[i] = u32::from_be_bytes([word[0], word[1], word[2], word[3]]);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
        }
        let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh] = h;
        for i in 0..64 {
            let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
            let ch = (e & f) ^ (!e & g);
            let t1 = hh.wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
            let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);
            hh = g;
            g = f;
            f = e;
            e = d.wrapping_add(t1);
            d = c;
            c = b;
            b = a;
            a = t1.wrapping_add(t2);
        }
        for (slot, v) in h.iter_mut().zip([a, b, c, d, e, f, g, hh]) {
            *slot = slot.wrapping_add(v);
        }
    }
    h.iter().map(|x| format!("{x:08x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The fonts get their own section, after the assets.
    #[test]
    fn faces_render_in_their_own_section() {
        let row = |pairs: &[(&str, &str)]| pairs.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect::<BTreeMap<_, _>>();
        let face = row(&[
            ("face", "Hack"),
            ("author", "Source Foundry Authors"),
            ("copyright", "Copyright (c) 2018 Source Foundry Authors"),
            ("source", "epaint_default_fonts 0.36.2"),
            ("licence", "MIT"),
        ]);
        assert!(!render(&[], &[]).contains("## Fonts"));
        let out = render(&[], &[face]);
        assert!(out.contains("## Fonts"), "{out}");
        assert!(
            out.contains("| Hack | Source Foundry Authors | Copyright (c) 2018 Source Foundry Authors | epaint_default_fonts 0.36.2 | MIT |"),
            "{out}"
        );
    }

    /// A face from a crate is held to the crate version Cargo.lock locks.
    #[test]
    fn a_face_from_a_crate_must_name_the_locked_version_of_its_crate() {
        let lock = "version = 4\n\n[[package]]\nname = \"fonts\"\nversion = \"0.2.0\"\ndependencies = [\n \"x\",\n]\n\n[[package]]\nname = \"x\"\nversion = \"1.0.0\"\n";
        let locked = locked_packages(lock);
        assert_eq!(locked.len(), 2, "{locked:?}");
        let row = |version: &str, source: &str| {
            [("face", "F"), ("crate", "fonts"), ("version", version), ("source", source)]
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect::<BTreeMap<_, _>>()
        };
        assert_eq!(face_version_problem(&row("0.2.0", "fonts 0.2.0, f.ttf"), &locked), None);
        let stale = face_version_problem(&row("0.1.0", "fonts 0.1.0, f.ttf"), &locked).unwrap();
        assert!(stale.contains("names fonts 0.1.0, but Cargo.lock holds 0.2.0"), "{stale}");
        let unnamed = face_version_problem(&row("0.2.0", "somewhere else"), &locked).unwrap();
        assert!(unnamed.contains("does not start with \"fonts 0.2.0\""), "{unnamed}");
        assert!(face_version_problem(&row("0.2.0", "fonts 0.2.0"), &locked).is_none(), "the version may end the source");
        assert!(face_version_problem(&row("0.2.0", "fonts 0.2.01, f.ttf"), &locked).is_some(), "0.2.01 is another version");
        // An unused patch locks nothing; a crate locked twice lists both versions; an unknown one says so.
        let patched = format!("{lock}\n[[patch.unused]]\nname = \"fonts\"\nversion = \"0.1.0\"\n");
        assert!(face_version_problem(&row("0.1.0", "fonts 0.1.0"), &locked_packages(&patched)).is_some());
        let twice = format!("{lock}\n[[package]]\nname = \"fonts\"\nversion = \"0.3.0\"\n");
        let both = face_version_problem(&row("0.1.0", "fonts 0.1.0"), &locked_packages(&twice)).unwrap();
        assert!(both.contains("Cargo.lock holds 0.2.0, 0.3.0"), "{both}");
        let mut unknown = row("1.0.0", "other 1.0.0");
        unknown.insert("crate".into(), "other".into());
        assert!(face_version_problem(&unknown, &locked).unwrap().contains("holds no such crate"));
    }

    #[test]
    fn sha256_matches_the_standard_vectors() {
        assert_eq!(sha256_hex(b""), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
        assert_eq!(sha256_hex(b"abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
        assert_eq!(sha256_hex(&[b'a'; 1000]), "41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3");
    }
}
